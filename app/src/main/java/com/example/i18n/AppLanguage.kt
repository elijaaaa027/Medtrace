  fun forLanguage(lang: AppLanguage): AppStrings =
    when (lang) {
      AppLanguage.EN -> english
      AppLanguage.TA -> tamil
      AppLanguage.HI -> hindi
    }

  fun getTimeBasedGreeting(lang: AppLanguage, rawUserName: String): String {
    val name = rawUserName.trim().ifBlank { "Patient" }
    val cal = Calendar.getInstance(TimeZone.getDefault())
    val hour = cal.get(Calendar.HOUR_OF_DAY)
    return when (lang) {
      AppLanguage.EN ->
        when (hour) {
          in 5..11 -> "Good morning, $name"
          in 12..16 -> "Good afternoon, $name"
          in 17..20 -> "Good evening, $name"
          else -> "Good night, $name"
        }
      AppLanguage.TA ->
        when (hour) {
          in 5..11 -> "காலை வணக்கம், $name (Good morning, $name)"
          in 12..16 -> "மதிய வணக்கம், $name (Good afternoon, $name)"
          in 17..20 -> "மாலை வணக்கம், $name (Good evening, $name)"
          else -> "இரவு வணக்கம், $name (Good night, $name)"
        }
      AppLanguage.HI ->
        when (hour) {
          in 5..11 -> "सुप्रभात, $name (Good morning, $name)"
          in 12..16 -> "नमस्कार, $name (Good afternoon, $name)"
          in 17..20 -> "शुभ संध्या, $name (Good evening, $name)"
          else -> "शुभ रात्रि, $name (Good night, $name)"
        }
    }
  }

  fun formatLocalTimestamp(epochMillis: Long): String {
    val sdf = SimpleDateFormat("dd MMM yyyy, hh:mm a z", Locale.getDefault())
    sdf.timeZone = TimeZone.getDefault()
    return sdf.format(Date(epochMillis))
  }

  fun currentLocalDateString(): String {
    val sdf = SimpleDateFormat("yyyy-MM-dd", Locale.getDefault())
    sdf.timeZone = TimeZone.getDefault()
    return sdf.format(Date())
  }

  fun currentLocalTimeString(): String {
    val sdf = SimpleDateFormat("hh:mm a", Locale.getDefault())
    sdf.timeZone = TimeZone.getDefault()
    return sdf.format(Date())
  }
